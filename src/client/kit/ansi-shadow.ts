const ROWS = 6;

/** `text` in ANSI Shadow block letters, rows joined by newlines. Lowercase is uppercased; other characters become spaces. */
export function renderAnsiShadow(text: string): string {
  const glyphs = [...text.toUpperCase()].map((c) => ANSI_SHADOW[c] ?? ANSI_SHADOW[" "]!);
  return Array.from({ length: ROWS }, (_, r) => glyphs.map((g) => g[r]).join("")).join("\n");
}

/**
 * Splits a (possibly mid-decrypt) frame of `art` into the three stacked layers the banner draws: solid `█`
 * blocks, the box-drawing shadow, and the not-yet-settled noise. Each layer keeps every row and column, so the
 * `<pre>`s line up exactly; `noise` is null once nothing is scrambled.
 */
export function bannerLayers(
  art: string,
  frame: string,
): { block: string; shadow: string; noise: string | null } {
  let block = "";
  let shadow = "";
  let noise = "";
  let scrambled = false;
  for (let i = 0; i < art.length; i++) {
    const ch = art[i]!;
    const f = frame[i] ?? ch;
    if (ch === "\n") {
      block += ch;
      shadow += ch;
      noise += ch;
    } else if (f === ch) {
      block += ch === "█" ? ch : " ";
      shadow += ch === "█" ? " " : ch;
      noise += " ";
    } else {
      scrambled = true;
      block += " ";
      shadow += " ";
      noise += f;
    }
  }
  return { block, shadow, noise: scrambled ? noise : null };
}
